"""Build single-file Supabase dashboard deployments from the tested modules."""
from pathlib import Path
import re
import sys
root = Path(__file__).resolve().parents[1]
functions = {
    'bp-publishing-desk': ['handler.ts', 'outlook.ts'],
    'bp-reading-create-checkout': ['handler.ts'],
    'bp-reading-deliver-epub': ['handler.ts'],
    'bp-reading-shopify-webhook': ['handler.ts', 'shopify-auth.ts', 'shopify-service.ts'],
    'bp-reading-reconcile-order': [
        '../bp-reading-shopify-webhook/handler.ts',
        '../bp-reading-shopify-webhook/shopify-auth.ts',
        '../bp-reading-shopify-webhook/shopify-service.ts',
        'handler.ts',
    ],
}
failed = False
for name, modules in functions.items():
    source = root / 'supabase/functions' / name
    imports, pieces = [], []
    for filename in [*modules, 'index.ts']:
        body = []
        for line in (source / filename).read_text().splitlines():
            if line.startswith('import '):
                if not line.rstrip().endswith(';'):
                    raise RuntimeError('Update bundler for a multiline import before proceeding')
                if not re.search(r"from\s*['\"]\.\.?/", line) and line not in imports:
                    imports.append(line)
            else:
                body.append(line)
        pieces.append('\n'.join(body).strip())
    text = '// Generated by scripts/bundle-edge-functions.py; edit the source modules.\n'
    text += '// Paste this entire file into index.ts in the matching Supabase function.\n'
    text += '\n'.join(imports) + '\n\n' + '\n\n'.join(pieces) + '\n'
    target = root / 'supabase/dashboard' / (name + '.ts')
    if '--check' in sys.argv:
        if not target.exists() or target.read_text() != text:
            print('Stale dashboard bundle:', target.name)
            failed = True
    else:
        target.parent.mkdir(parents=True, exist_ok=True)
        target.write_text(text)
if failed:
    raise SystemExit(1)
